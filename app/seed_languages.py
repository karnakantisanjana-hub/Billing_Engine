def run():
    db = SessionLocal()
    try:
        for code, name, native_name, flag_emoji in LANGUAGES:
            existing = db.query(Language).filter(Language.code == code).first()
            if existing:
                existing.name = name
                existing.native_name = native_name
                existing.flag_emoji = flag_emoji
                existing.is_active = True
            else:
                db.add(Language(
                    code=code, name=name, native_name=native_name,
                    flag_emoji=flag_emoji, is_active=True,
                ))
        db.commit()

        inserted, updated = 0, 0
        for key, lang_map in TRANSLATIONS.items():
            for lang_code, value in lang_map.items():
                row = (
                    db.query(Translation)
                    .filter(Translation.key == key, Translation.language_code == lang_code)
                    .first()
                )
                if row:
                    row.value = value
                    updated += 1
                else:
                    db.add(Translation(
                        key=key, language_code=lang_code, value=value, category=CATEGORY,
                    ))
                    inserted += 1
        db.commit()
        print(f"Languages seeded: {len(LANGUAGES)}")
        print(f"Translations inserted: {inserted}, updated: {updated}")
    finally:
        db.close()


if __name__ == "__main__":
    run()